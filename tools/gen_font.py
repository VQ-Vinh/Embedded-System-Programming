first, last = 0x20, 0x7E
out = []
for c in range(first, last + 1):
    ch = chr(c)
    rows = G.get(ch.upper()) if ch.isalpha() else G.get(ch)
    if rows is None: rows = G['?']
    cols = []
    for x in range(5):
        b = 0
        for y in range(7):
            if rows[y][x] == '#': b |= 1 << y
        cols.append('0x%02X' % b)
    disp = ch.replace('\\', 'backslash')
    out.append('    {%s}, /* 0x%02X %s */' % (', '.join(cols), c, disp if ch not in '*/' else repr(ch)))
